"""Things the SDK hides: exact headers, XML bodies and error shapes on the wire.

Requests are authorized with an account SAS generated by the SDK, so no request
signing is needed here.
"""

import base64
import email.utils
import hashlib
import re
import uuid
import xml.etree.ElementTree as ET
from datetime import datetime, timedelta, timezone

import pytest
import requests
from azure.storage.blob import AccountSasPermissions, CorsRule, ResourceTypes, generate_account_sas

HTTP_DATE = re.compile(r"^[A-Z][a-z]{2}, \d{2} [A-Z][a-z]{2} \d{4} \d{2}:\d{2}:\d{2} GMT$")


@pytest.fixture
def sas(account_name, account_key):
    return generate_account_sas(
        account_name,
        account_key,
        resource_types=ResourceTypes(service=True, container=True, object=True),
        permission=AccountSasPermissions(
            read=True, write=True, delete=True, list=True, add=True, create=True, update=True, process=True
        ),
        expiry=datetime.now(timezone.utc) + timedelta(hours=1),
    )


@pytest.fixture
def u(container, sas):
    """Build a URL for a blob (or the container when name is None) with the SAS attached."""

    def build(name=None, **params):
        base = container.url if name is None else f"{container.url}/{name}"
        query = "&".join([f"{k}={v}" for k, v in params.items()] + [sas])
        return f"{base}?{query}"

    return build


def _error(r):
    root = ET.fromstring(r.content.decode("utf-8-sig"))
    assert root.tag == "Error"
    return root


# --- error shape -----------------------------------------------------------


def test_error_body_is_xml_with_code_and_message(u):
    r = requests.get(u("missing"))
    assert r.status_code == 404
    assert r.headers["Content-Type"].startswith("application/xml")
    err = _error(r)
    assert err.findtext("Code") == "BlobNotFound"
    msg = err.findtext("Message")
    assert msg.startswith("The specified blob does not exist.")
    assert "RequestId:" in msg and "Time:" in msg


def test_error_response_has_x_ms_error_code_header_matching_body(u):
    r = requests.get(u("missing"))
    assert r.headers["x-ms-error-code"] == _error(r).findtext("Code") == "BlobNotFound"


