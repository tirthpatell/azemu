def test_get_if_none_match_with_current_etag_is_304(u, container):
    container.upload_blob("c", b"x")
    etag = requests.head(u("c")).headers["ETag"]
    r = requests.get(u("c"), headers={"If-None-Match": etag})
    assert r.status_code == 304
    assert r.content == b""
    # Real Azure's 304 carries only x-ms-error-code (recording
    # test_get_blob_with_if_none_match_fail): no ETag, no Last-Modified.
    assert r.headers["x-ms-error-code"] == "ConditionNotMet"
    assert "ETag" not in r.headers


@pytest.mark.parametrize("method", ["GET", "HEAD"])
def test_failed_read_condition_304_carries_condition_not_met_header(u, container, method):
    # Real Azure (recordings test_get_blob_with_if_none_match_fail and
    # test_get_blob_properties_with_if_modified_fail): the 304 has no body but
    # does carry x-ms-error-code. The SDK relies on this header to pick its exception.
    container.upload_blob("c3", b"x")
    etag = requests.head(u("c3")).headers["ETag"]
    r = requests.request(method, u("c3"), headers={"If-None-Match": etag})
    assert r.status_code == 304
    assert r.content == b""
    assert r.headers["x-ms-error-code"] == "ConditionNotMet"
    future = email.utils.format_datetime(datetime.now(timezone.utc) + timedelta(days=1), usegmt=True)
    r = requests.request(method, u("c3"), headers={"If-Modified-Since": future})
    assert r.status_code == 304
    assert r.content == b""
    assert r.headers["x-ms-error-code"] == "ConditionNotMet"


