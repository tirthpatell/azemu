def test_cors_preflight_uses_service_cors_rules(service, container):
    service.set_service_properties(
        cors=[CorsRule(["https://app.example.com"], ["GET", "PUT"], allowed_headers=["x-ms-*"], max_age_in_seconds=60)]
    )
    try:
        r = requests.options(
            f"{container.url}/anything",
            headers={
                "Origin": "https://app.example.com",
                "Access-Control-Request-Method": "GET",
                "Access-Control-Request-Headers": "x-ms-version",
            },
        )
        assert r.status_code == 200
        assert r.headers["Access-Control-Allow-Origin"] == "https://app.example.com"
        assert "GET" in r.headers["Access-Control-Allow-Methods"]
        assert r.headers["Access-Control-Max-Age"] == "60"
        bad = requests.options(
            f"{container.url}/anything",
            headers={"Origin": "https://evil.example.com", "Access-Control-Request-Method": "GET"},
        )
        assert bad.status_code == 403
    finally:
        service.set_service_properties(cors=[])
