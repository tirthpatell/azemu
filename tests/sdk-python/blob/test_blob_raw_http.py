def test_list_blobs_maxresults_returns_next_marker(u, container):
    for n in ("a", "b", "c"):
        container.upload_blob(n, b"x")
    r = requests.get(u(None, restype="container", comp="list", maxresults="2"))
    root = ET.fromstring(r.content.decode("utf-8-sig"))
    assert root.findtext("MaxResults") == "2"
    assert [b.findtext("Name") for b in root.findall("Blobs/Blob")] == ["a", "b"]
    marker = root.findtext("NextMarker")
    assert marker
    r2 = requests.get(u(None, restype="container", comp="list", maxresults="2", marker=requests.utils.quote(marker, safe="")))
    root2 = ET.fromstring(r2.content.decode("utf-8-sig"))
    assert [b.findtext("Name") for b in root2.findall("Blobs/Blob")] == ["c"]
    assert not (root2.findtext("NextMarker") or "")


