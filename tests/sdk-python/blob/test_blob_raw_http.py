def test_list_blobs_xml_shape(u, container):
    container.upload_blob("listed", b"12345", metadata={"k": "v"})
    r = requests.get(u(None, restype="container", comp="list", include="metadata"))
    assert r.status_code == 200
    assert r.headers["Content-Type"].startswith("application/xml")
    root = ET.fromstring(r.content.decode("utf-8-sig"))
    assert root.tag == "EnumerationResults"
    assert root.attrib["ContainerName"] == container.container_name
    assert "ServiceEndpoint" in root.attrib
    blob = root.find("Blobs/Blob")
    assert blob.findtext("Name") == "listed"
    props = blob.find("Properties")
    assert props.findtext("Content-Length") == "5"
    assert props.findtext("BlobType") == "BlockBlob"
    assert props.findtext("LeaseState") == "available"
    assert HTTP_DATE.match(props.findtext("Last-Modified"))
    assert not props.findtext("Etag").startswith('"')
    assert blob.find("Metadata").findtext("k") == "v"
    nm = root.find("NextMarker")
    assert nm is not None and not (nm.text or "")


