def test_put_blob_response_headers(u):
    data = b"hello headers"
    r = requests.put(u("put"), data=data, headers={"x-ms-blob-type": "BlockBlob"})
    assert r.status_code == 201
    assert re.fullmatch(r'"[^"]+"', r.headers["ETag"])
    assert HTTP_DATE.match(r.headers["Last-Modified"])
    assert r.headers["Content-MD5"] == base64.b64encode(hashlib.md5(data).digest()).decode()
    assert r.headers["x-ms-request-server-encrypted"] == "true"
    assert r.content == b""


