#!/usr/bin/env python3
"""Generates src/schemas.rs from Apache Kafka's own message definitions
(clients/src/main/resources/common/message/*.json, branch 3.9).

    python3 schema/gen.py <dir with the JSON files> > src/schemas.rs

The files used for src/schemas.rs are those of the Apache Kafka tag 3.9.0 (https://github.com/apache/kafka, Apache-2.0):
`curl -O https://raw.githubusercontent.com/apache/kafka/3.9.0/clients/src/main/resources/common/message/<Api><Request|Response>.json`.
Run on those files this script writes src/schemas.rs byte for byte.

The wire layout of every message is data in this file, so the codec in src/schema.rs is one interpreter for all
requests and responses. Run it again to add an API (add the name to APIS) or a newer version."""
import json, re, sys

APIS = ["ApiVersions", "Metadata", "Produce", "Fetch", "ListOffsets", "FindCoordinator", "JoinGroup", "SyncGroup",
        "Heartbeat", "LeaveGroup", "OffsetCommit", "OffsetFetch", "DescribeGroups", "ListGroups", "InitProducerId",
        "SaslHandshake", "SaslAuthenticate", "CreateTopics", "DeleteTopics", "CreatePartitions", "DescribeConfigs"]
MAX = "i16::MAX"

def load(p):
    t = re.sub(r'^\s*//.*$', '', open(p).read(), flags=re.M)
    return json.loads(t)

def vr(s):
    s = s.strip()
    if s == "none": return (1, 0)
    if s.endswith("+"): return (int(s[:-1]), None)
    if "-" in s:
        a, b = s.split("-"); return (int(a), int(b))
    return (int(s), int(s))

def vs(t):
    return (str(t[0]), MAX if t[1] is None else str(t[1]))

PRIM = {"int8": "I8", "int16": "I16", "int32": "I32", "int64": "I64", "uint16": "U16", "float64": "F64", "bool": "Bool",
        "string": "Str", "bytes": "Bytes", "records": "Records", "uuid": "Uuid"}

def ty(name, f, common):
    if name.startswith("[]"):
        return "Ty::Array(&" + ty(name[2:], f, common) + ")"
    if name in PRIM: return "Ty::" + PRIM[name]
    fields = f.get("fields") or common.get(name)
    if fields is None: raise Exception("unknown type " + name)
    return "Ty::Struct(&[" + ", ".join(field(x, common) for x in fields) + "])"

def dflt(f):
    d = f.get("default")
    if d is None or d == "": return "Def::Zero"
    if isinstance(d, bool): return "Def::Int(1)" if d else "Def::Zero"
    if isinstance(d, int): return "Def::Int(%d)" % d
    if d == "null": return "Def::Null"
    if d == "true": return "Def::Int(1)"
    if d == "false": return "Def::Zero"
    try:
        return "Def::Int(%d)" % int(d, 0)
    except ValueError:
        return "Def::Zero"

def field(f, common):
    lo, hi = vs(vr(f["versions"]))
    if "nullableVersions" in f:
        nl, nh = vs(vr(f["nullableVersions"]))
    else:
        nl, nh = "1", "0"
    tag = f.get("tag", -1)
    return 'f("%s", %s, %s, %s, %s, %s, %d, %s)' % (f["name"], ty(f["type"], f, common), lo, hi, nl, nh, tag, dflt(f))

HEADER = [
    "// Generated by schema/gen.py from Apache Kafka 3.9 message definitions. Do not edit.",
    "//",
    "// Derived from the message definitions of Apache Kafka (clients/src/main/resources/common/message/*.json, tag 3.9.0),",
    "// Copyright The Apache Software Foundation, licensed under the Apache License, Version 2.0",
    "// (https://www.apache.org/licenses/LICENSE-2.0; the text is LICENSE-APACHE at the root of this repository).",
    "// This file holds the field layout of the requests and responses that Kafka's JSON files describe (names, types,",
    "// versions); it was changed from them by turning the JSON into Rust tables and by leaving out every API this emulator",
    "// does not serve. See NOTICE.",
]
out = HEADER + [
       "use crate::schema::{f, Def, MessageSchema, Ty};", ""]
reqs, resps = [], []
for api in APIS:
    for kind in ("Request", "Response"):
        d = load("%s/%s%s.json" % (sys.argv[1], api, kind))
        common = {c["name"]: c["fields"] for c in d.get("commonStructs", [])}
        name = "%s_%s" % (re.sub(r'(?<!^)(?=[A-Z])', '_', api).upper(), kind.upper())
        fl = vr(d["flexibleVersions"])[0] if d["flexibleVersions"] != "none" else 32767
        lo, hi = vr(d["validVersions"])
        out.append("pub static %s: MessageSchema = MessageSchema { name: \"%s%s\", api_key: %d, min: %d, max: %d, flexible_from: %d, fields: &[%s] };" % (
            name, api, kind, d["apiKey"], lo, hi, fl, ", ".join(field(x, common) for x in d["fields"])))
        (reqs if kind == "Request" else resps).append(name)
out.append("")
out.append("pub static REQUESTS: &[&MessageSchema] = &[%s];" % ", ".join("&" + n for n in reqs))
out.append("pub static RESPONSES: &[&MessageSchema] = &[%s];" % ", ".join("&" + n for n in resps))
print("\n".join(out))
